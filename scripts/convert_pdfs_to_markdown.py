#!/usr/bin/env python3
"""Convert the PDF corpus to page-preserving Markdown.

The repository's PDFs are books and scanned book exports with mixed-quality
text layers.  pdftotext is used instead of OCR because every source currently
has an extractable text layer; empty pages are retained and reported so an
OCR follow-up can be targeted rather than silently dropping content.
"""

from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path


def pdf_metadata(pdf: Path) -> dict[str, str]:
    result = subprocess.run(
        ["pdfinfo", str(pdf)],
        check=True,
        capture_output=True,
        text=True,
    )
    metadata: dict[str, str] = {}
    for line in result.stdout.splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        metadata[key.strip()] = value.strip()
    return metadata


def extract_text(pdf: Path) -> tuple[str, str]:
    result = subprocess.run(
        ["pdftotext", "-layout", "-enc", "UTF-8", str(pdf), "-"],
        check=False,
        capture_output=True,
        text=True,
        errors="replace",
    )
    stderr = result.stderr.strip()
    if result.returncode != 0:
        raise RuntimeError(stderr or f"pdftotext exited with {result.returncode}")
    return result.stdout, stderr


def safe_heading(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def convert(pdf: Path, output_dir: Path, root: Path) -> dict[str, str | int]:
    metadata = pdf_metadata(pdf)
    raw_text, warnings = extract_text(pdf)
    pages = raw_text.replace("\r\n", "\n").replace("\r", "\n").split("\f")
    # pdftotext may append a final form feed. It is not a source page.
    if pages and not pages[-1].strip():
        pages.pop()

    title = safe_heading(metadata.get("Title") or pdf.stem)
    relative_source = pdf.relative_to(root).as_posix()
    relative_output = Path(pdf.stem + ".md")
    output = output_dir / relative_output
    nonempty_pages = sum(bool(page.strip()) for page in pages)
    characters = sum(len(page) for page in pages)

    lines = [
        "---",
        f"title: {title}",
        f"source_pdf: {relative_source}",
        f"pages: {len(pages)}",
        "extraction: pdftotext -layout",
        f"nonempty_text_pages: {nonempty_pages}",
        f"text_characters: {characters}",
        "ocr_used: false",
        "---",
        "",
        f"# {title}",
        "",
        f"> Source: `{relative_source}`",
        ">",
        "> This Markdown file is a page-preserving text extraction. Layout, figures,",
        "> equations, and text embedded only in images may require separate review.",
        "",
    ]
    if metadata.get("Author"):
        lines.extend([f"**Authors:** {metadata['Author']}", ""])
    if warnings:
        lines.extend([f"> pdftotext warning: {warnings}", ""])

    for number, page in enumerate(pages, start=1):
        lines.extend([f"## Page {number}", ""])
        content = page.strip("\n")
        lines.extend(content.splitlines() if content else ["*(No text extracted from this page.)*"])
        lines.append("")

    output.write_text("\n".join(lines), encoding="utf-8")
    return {
        "source": relative_source,
        "output": output.relative_to(root).as_posix(),
        "pages": len(pages),
        "nonempty_text_pages": nonempty_pages,
        "text_characters": characters,
        "status": "ok",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("docs/pdfs"))
    parser.add_argument("--output", type=Path, default=Path("markdown"))
    args = parser.parse_args()

    root = Path.cwd()
    source_dir = (root / args.source).resolve()
    output_dir = (root / args.output).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    pdfs = sorted(source_dir.glob("*.pdf"))
    if not pdfs:
        parser.error(f"no PDFs found under {source_dir}")

    report: list[dict[str, str | int]] = []
    failures: list[str] = []
    for pdf in pdfs:
        try:
            item = convert(pdf, output_dir, root)
        except Exception as exc:  # retain a report for a source that needs OCR
            item = {
                "source": pdf.relative_to(root).as_posix(),
                "output": "",
                "pages": 0,
                "nonempty_text_pages": 0,
                "text_characters": 0,
                "status": f"failed: {exc}",
            }
            failures.append(f"{pdf.name}: {exc}")
        report.append(item)
        print(f"{item['status']}: {item['source']}")

    report_lines = [
        "# PDF conversion report",
        "",
        "Generated by `scripts/convert_pdfs_to_markdown.py`.",
        "",
        "| Source | Markdown | Pages | Nonempty text pages | Characters | Status |",
        "|---|---|---:|---:|---:|---|",
    ]
    for item in report:
        output = item["output"] or "—"
        report_lines.append(
            f"| `{item['source']}` | `{output}` | {item['pages']} | "
            f"{item['nonempty_text_pages']} | {item['text_characters']} | {item['status']} |"
        )
    report_lines.extend(
        [
            "",
            "The conversion preserves the source PDFs. A page with no extracted text is",
            "retained as an explicit placeholder so OCR gaps remain visible.",
            "",
        ]
    )
    (output_dir / "conversion-report.md").write_text("\n".join(report_lines), encoding="utf-8")
    if failures:
        print("Conversion failures:", *failures, sep="\n- ")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
